-- =========================================================================
-- V1__initial_schema.sql: Khởi tạo toàn bộ 10 bảng dữ liệu cho StudyHub AI
-- Hệ CSDL: H2 Database (Tương thích chuẩn ANSI SQL & PostgreSQL/MySQL)
-- Framework: Flyway Database Migration
-- =========================================================================

-- 1. BẢNG COURSES (Quản lý Môn học - TÙNG Leader)
CREATE TABLE IF NOT EXISTS courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    description VARCHAR(1000),
    color VARCHAR(100) DEFAULT 'from-indigo-600 to-purple-600',
    icon VARCHAR(50) DEFAULT 'fa-book-open',
    semester VARCHAR(50) DEFAULT 'Fall 2026',
    credits INT DEFAULT 3,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_courses_code ON courses(code);

-- 2. BẢNG DOCUMENTS (Tài liệu PDF Giáo trình - BÌNH)
CREATE TABLE IF NOT EXISTS documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_path VARCHAR(500),
    file_type VARCHAR(50) DEFAULT 'application/pdf',
    file_size BIGINT,
    total_pages INT DEFAULT 0,
    total_chunks INT DEFAULT 0,
    status VARCHAR(30) DEFAULT 'UPLOADED',
    error_message VARCHAR(1000),
    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_documents_course FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_documents_course ON documents(course_id);
CREATE INDEX IF NOT EXISTS idx_documents_status ON documents(status);

-- 3. BẢNG CHUNKS (Đoạn văn bản & Vector 768d - BÌNH)
CREATE TABLE IF NOT EXISTS chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    course_id BIGINT NOT NULL,
    chunk_index INT NOT NULL,
    content CLOB NOT NULL,
    page_number INT DEFAULT 1,
    word_count INT DEFAULT 0,
    token_count INT DEFAULT 0,
    embedding_vector CLOB,
    has_embedding BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_chunks_document FOREIGN KEY (document_id) REFERENCES documents(id) ON DELETE CASCADE,
    CONSTRAINT fk_chunks_course FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_chunks_course ON chunks(course_id);
CREATE INDEX IF NOT EXISTS idx_chunks_doc ON chunks(document_id);
CREATE INDEX IF NOT EXISTS idx_chunks_embedding ON chunks(has_embedding);

-- 4. BẢNG CHAT_SESSIONS (Phiên trò chuyện RAG theo môn - BÌNH)
CREATE TABLE IF NOT EXISTS chat_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_chat_sessions_course FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_chat_sessions_course ON chat_sessions(course_id);

-- 5. BẢNG CHAT_MESSAGES (Lịch sử tin nhắn Markdown & Citations - BÌNH)
CREATE TABLE IF NOT EXISTS chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    sender VARCHAR(20) NOT NULL,
    content CLOB NOT NULL,
    rag_context CLOB,
    token_count INT DEFAULT 0,
    sent_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_chat_messages_session FOREIGN KEY (session_id) REFERENCES chat_sessions(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_chat_messages_session ON chat_messages(session_id);
CREATE INDEX IF NOT EXISTS idx_chat_messages_sent_at ON chat_messages(sent_at);

-- 6. BẢNG STUDY_PLANS (Lộ trình học tập vừa sức - THẮNG)
CREATE TABLE IF NOT EXISTS study_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    hours_per_week INT DEFAULT 6,
    selected_days VARCHAR(100),
    exam_date DATE,
    goal VARCHAR(500),
    status VARCHAR(30) DEFAULT 'ACTIVE',
    progress_percent INT DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_study_plans_course FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_study_plans_course ON study_plans(course_id);

-- 7. BẢNG STUDY_TASKS (Từng nhiệm vụ học tập theo tuần/ngày - THẮNG)
CREATE TABLE IF NOT EXISTS study_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    week_number INT NOT NULL,
    day_of_week VARCHAR(30) NOT NULL,
    task_title VARCHAR(255) NOT NULL,
    task_description TEXT,
    duration_minutes INT DEFAULT 120,
    is_completed BOOLEAN DEFAULT FALSE,
    completed_at TIMESTAMP,
    sort_order INT DEFAULT 0,
    CONSTRAINT fk_study_tasks_plan FOREIGN KEY (plan_id) REFERENCES study_plans(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_study_tasks_plan ON study_tasks(plan_id);
CREATE INDEX IF NOT EXISTS idx_study_tasks_completed ON study_tasks(is_completed);

-- 8. BẢNG QUIZZES (Đề thi trắc nghiệm AI theo chương - NHẬT)
CREATE TABLE IF NOT EXISTS quizzes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    chapter_topic VARCHAR(255),
    difficulty VARCHAR(20) DEFAULT 'MEDIUM',
    total_questions INT DEFAULT 5,
    time_limit_minutes INT DEFAULT 15,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_quizzes_course FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_quizzes_course ON quizzes(course_id);
CREATE INDEX IF NOT EXISTS idx_quizzes_difficulty ON quizzes(difficulty);

-- 9. BẢNG QUIZ_QUESTIONS (Câu hỏi trắc nghiệm A/B/C/D & Lời giải - NHẬT)
CREATE TABLE IF NOT EXISTS quiz_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL,
    question_text TEXT NOT NULL,
    option_a TEXT NOT NULL,
    option_b TEXT NOT NULL,
    option_c TEXT NOT NULL,
    option_d TEXT NOT NULL,
    correct_answer VARCHAR(5) NOT NULL,
    explanation TEXT,
    sort_order INT DEFAULT 1,
    CONSTRAINT fk_quiz_questions_quiz FOREIGN KEY (quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_quiz_questions_quiz ON quiz_questions(quiz_id);

-- 10. BẢNG QUIZ_ATTEMPTS (Lịch sử làm bài thi & chấm điểm - NHẬT)
CREATE TABLE IF NOT EXISTS quiz_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL,
    student_name VARCHAR(100) DEFAULT 'Sinh viên',
    total_score DOUBLE NOT NULL,
    correct_count INT NOT NULL,
    total_count INT NOT NULL,
    user_answers CLOB,
    time_spent_seconds INT DEFAULT 0,
    completed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_quiz_attempts_quiz FOREIGN KEY (quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_quiz_attempts_quiz ON quiz_attempts(quiz_id);
CREATE INDEX IF NOT EXISTS idx_quiz_attempts_completed_at ON quiz_attempts(completed_at);

-- 11. BẢNG USERS (Quản lý Tài khoản & Xác thực JWT - TRƯỜNG)
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    role VARCHAR(30) DEFAULT 'ROLE_STUDENT',
    avatar VARCHAR(255) DEFAULT 'https://api.dicebear.com/7.x/bottts/svg?seed=student',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_users_username ON users(username);
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);

